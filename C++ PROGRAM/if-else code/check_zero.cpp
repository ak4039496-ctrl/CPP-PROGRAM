#include <iostream>
using namespace std;

int main() {
    int num;
    cout << "Enter a number:- ";
    cin >> num;

    if (num == 0) {
        cout << "The number is Zero." << endl;
    } else {
        cout << "The number is not Zero." << endl;
    }

    return 0;
}
